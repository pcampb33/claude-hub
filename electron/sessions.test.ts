import { test } from 'node:test'
import assert from 'node:assert/strict'
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { isHeadlessSession, isHeadlessSessionCached, parseTranscriptFile, readableTurn, readSessionTitle, unwrapPasted } from './sessions.ts'

function tmpJsonl(lines: string[]): string {
  const file = path.join(fs.mkdtempSync(path.join(os.tmpdir(), 'hub-sessions-')), 's.jsonl')
  fs.writeFileSync(file, lines.join('\n') + '\n')
  return file
}

test('isHeadlessSession flags a headless sdk-cli (claude -p) transcript', async () => {
  const file = tmpJsonl([
    JSON.stringify({ type: 'queue-operation' }),
    JSON.stringify({ message: { role: 'user', content: 'triage this' }, entrypoint: 'sdk-cli' }),
  ])
  assert.equal(await isHeadlessSession(file), true)
})

test('isHeadlessSession keeps a real interactive cli session', async () => {
  const file = tmpJsonl([JSON.stringify({ message: { role: 'user', content: 'fix the bug' }, entrypoint: 'cli' })])
  assert.equal(await isHeadlessSession(file), false)
})

test('isHeadlessSession keys off the first real user line, ignoring assistant and sidechain turns', async () => {
  const file = tmpJsonl([
    JSON.stringify({ message: { role: 'assistant', content: 'hi' }, entrypoint: 'sdk-cli' }),
    JSON.stringify({ message: { role: 'user', content: 'subagent' }, isSidechain: true, entrypoint: 'sdk-cli' }),
    JSON.stringify({ message: { role: 'user', content: 'the real prompt' }, entrypoint: 'cli' }),
  ])
  assert.equal(await isHeadlessSession(file), false)
})

test('isHeadlessSession treats a session with no user line as not headless', async () => {
  const file = tmpJsonl(['{}', JSON.stringify({ message: { role: 'assistant', content: 'x' } })])
  assert.equal(await isHeadlessSession(file), false)
})

test('parseTranscriptFile skips sidechain turns by default and includes them on request', async () => {
  const file = tmpJsonl([
    JSON.stringify({ message: { role: 'user', content: 'main turn' }, timestamp: 't1' }),
    JSON.stringify({ message: { role: 'assistant', content: 'subagent turn' }, isSidechain: true, timestamp: 't2' }),
  ])
  assert.deepEqual(
    (await parseTranscriptFile(file)).map((m) => m.text),
    ['main turn'],
  )
  assert.deepEqual(
    (await parseTranscriptFile(file, { includeSidechain: true })).map((m) => m.text),
    ['main turn', 'subagent turn'],
  )
})

// Verbatim from a real transcript: this is the first turn of most sessions.
const CLEAR_WRAPPER =
  '<command-name>/clear</command-name>\n            <command-message>clear</command-message>\n            <command-args></command-args>'

test('readableTurn renders a slash-command turn as its command, never as markup', () => {
  assert.equal(readableTurn(CLEAR_WRAPPER), '/clear')
  assert.equal(
    readableTurn('<command-name>/loop</command-name><command-message>loop</command-message><command-args>20m keep going</command-args>'),
    '/loop 20m keep going',
  )
})

test('readableTurn drops the harness-only command wrappers, which are nobody’s message', () => {
  assert.equal(readableTurn('<local-command-caveat>Caveat: The messages below were generated by the user…</local-command-caveat>'), null)
  assert.equal(readableTurn('<local-command-stdout>Compacted (ctrl+o to see full summary)</local-command-stdout>'), null)
})

test('readableTurn unwraps a task-notification down to the subagent’s report', () => {
  const notification =
    '<task-notification>\n<task-id>abc123</task-id>\n<tool-use-id>toolu_01</tool-use-id>\n' +
    '<status>completed</status>\n<summary>Agent "Explore IPC" finished</summary>\n' +
    '<result># Report\n\nThe answer is 42.</result>\n' +
    '<usage><subagent_tokens>110854</subagent_tokens><tool_uses>44</tool_uses><duration_ms>548985</duration_ms></usage>\n' +
    '</task-notification>'
  assert.equal(readableTurn(notification), '# Report\n\nThe answer is 42.')
})

test('readableTurn falls back to the summary when an agent produced no result', () => {
  const failed =
    '<task-notification>\n<task-id>abc123</task-id>\n<status>failed</status>\n' +
    '<summary>Agent "Explore IPC" hit the session limit</summary>\n' +
    '<usage><tool_uses>0</tool_uses></usage>\n</task-notification>'
  assert.equal(readableTurn(failed), 'Agent "Explore IPC" hit the session limit')
})

test('readableTurn leaves ordinary prose and quoted markup alone', () => {
  // This app is used to read code, and the curate hook's own transcripts embed
  // a rendered transcript inside the prompt — so only a turn that IS the whole
  // envelope may be stripped, never one that merely contains the same tags.
  const quoted = 'The envelope looks like <task-notification><result>x</result></task-notification> — note the <usage> tally.'
  assert.equal(readableTurn(quoted), quoted)
  assert.equal(readableTurn('if (x < y) { return "<command-name>" }'), 'if (x < y) { return "<command-name>" }')
})

// The read-side filter must stay out of the shared parser: curate-session.mjs
// gates a paid `claude -p` call on messages.length >= MIN_TURNS_FOR_REVIEW, so
// dropping these turns here would silently move hook spend (and the
// recursion-safety pre-filter that depends on short transcripts staying short).
test('parseTranscriptFile still returns control-markup turns verbatim, so turn counts are unmoved', async () => {
  const file = tmpJsonl([
    JSON.stringify({ message: { role: 'user', content: CLEAR_WRAPPER } }),
    JSON.stringify({ message: { role: 'user', content: '<local-command-stdout>ok</local-command-stdout>' } }),
    JSON.stringify({ message: { role: 'user', content: '<task-notification><result>done</result></task-notification>' } }),
  ])
  const messages = await parseTranscriptFile(file)
  assert.equal(messages.length, 3)
  assert.equal(messages[0].text, CLEAR_WRAPPER)
})

test('parseTranscriptFile skips api-request-blob lines, which carry role user but are no turn', async () => {
  const file = tmpJsonl([
    JSON.stringify({ message: { role: 'user', content: 'can you audit the view?' }, promptSource: 'typed' }),
    JSON.stringify({
      type: 'api-request-blob',
      hash: 'fa78',
      message: { role: 'user', content: [{ type: 'text', text: '<system-reminder>\nCodebase instructions…\n</system-reminder>\ncan you audit the view?' }] },
    }),
    JSON.stringify({ message: { role: 'assistant', content: 'Looking.' } }),
  ])
  assert.deepEqual(
    (await parseTranscriptFile(file)).map((m) => m.text),
    ['can you audit the view?', 'Looking.'],
  )
})

test('unwrapPasted keeps the paste and drops only the exact pasted_content wrapper', () => {
  // The real form: the closing tag repeats the id.
  assert.equal(unwrapPasted('<pasted_content id="db22">\nI\'m kind of stuck\n</pasted_content id="db22">'), "I'm kind of stuck")
  assert.equal(unwrapPasted('see <pasted_content id="1f44">a\nb</pasted_content> above'), 'see a\nb above')
  // Markup that is not the harness's exact wrapper is someone's text.
  assert.equal(unwrapPasted('the <pasted_content> tag'), 'the <pasted_content> tag')
})

test('readSessionTitle titles a pasted first prompt by the paste, not its wrapper', async () => {
  const file = tmpJsonl([JSON.stringify({ message: { role: 'user', content: '<pasted_content id="db22">\nI\'m kind of stuck\n</pasted_content id="db22">' } })])
  assert.equal(await readSessionTitle(file), "I'm kind of stuck")
})

test('isHeadlessSessionCached memoizes by path (returns the cached flag after the file is gone)', async () => {
  const file = tmpJsonl([JSON.stringify({ message: { role: 'user', content: 'x' }, entrypoint: 'sdk-cli' })])
  assert.equal(await isHeadlessSessionCached(file), true)
  fs.rmSync(file) // a second, uncached read would now throw — the cache must answer instead
  assert.equal(await isHeadlessSessionCached(file), true)
})
