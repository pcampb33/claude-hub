import { test } from 'node:test'
import assert from 'node:assert/strict'
import { buildTopicMoc, buildOriginMoc, mocExcerpt } from './vault-moc-core.ts'
import type { MocNote, MocEdge } from './vault-moc-core.ts'
import { detectCommunities } from '../shared/community.ts'
import { RELATED_BEGIN, RELATED_END } from './vault-related-core.ts'

function note(id: string, excerpt: string | null = null, project: string | null = null): MocNote {
  return { id, excerpt, project }
}

function edges(pairs: Array<[string, string]>): MocEdge[] {
  return pairs.map(([source, target]) => ({ source, target }))
}

// Two bridged triangles {a,b,c} / {d,e,f} (the community.test.ts fixture — one
// edge per unordered pair, adjacency symmetrizes) plus an edge-less note.
const NOTES = [
  note('a', 'alpha finding'),
  note('b', 'beta finding'),
  note('c', 'gamma finding'),
  note('d', 'delta finding'),
  note('e', 'epsilon finding'),
  note('f', 'zeta finding'),
  note('lonely', 'unconnected finding'),
]
const EDGES = edges([
  ['a', 'b'],
  ['b', 'c'],
  ['a', 'c'],
  ['d', 'e'],
  ['e', 'f'],
  ['d', 'f'],
  ['c', 'd'],
])
const CLUSTERS = detectCommunities({ notes: NOTES, edges: EDGES })

test('buildTopicMoc renders notice, counts, hub-headed cluster sections, and Unlinked', () => {
  const moc = buildTopicMoc(NOTES, EDGES, CLUSTERS)
  const lines = moc.split('\n')
  assert.match(lines[0], /^<!-- generated by claude-hub/)
  assert.equal(lines[1], '7 notes · 7 edges · 2 clusters')
  // Equal-size clusters tie-break by hub id: c (degree 3 via the bridge) then
  // d. Members are degree-desc, id asc — the hub leads its own section.
  assert.deepEqual(
    lines.filter((l) => l.startsWith('## ')),
    ['## Around: c', '## Around: d', '## Unlinked'],
  )
  assert.ok(moc.indexOf('## Around: c\n- [[c]] — gamma finding\n- [[a]] — alpha finding\n- [[b]] — beta finding') !== -1)
  assert.ok(moc.indexOf('## Unlinked\n- [[lonely]] — unconnected finding') !== -1)
})

test('buildTopicMoc truncates long excerpts to ~100 chars and skips the dash for excerpt-less notes', () => {
  const long = 'x'.repeat(150)
  const pair = [note('bare'), note('long', long)]
  const moc = buildTopicMoc(pair, edges([['bare', 'long']]), detectCommunities({ notes: pair, edges: edges([['bare', 'long']]) }))
  assert.ok(moc.includes(`- [[long]] — ${'x'.repeat(100)}…`))
  assert.ok(moc.includes('- [[bare]]\n'))
})

test('buildOriginMoc groups by project count desc with untagged last even when largest', () => {
  const moc = buildOriginMoc([
    note('n1', 'one', 'alpha'),
    note('n2', 'two', 'alpha'),
    note('n3', 'three', 'beta'),
    note('n4', 'four', null),
    note('n5', 'five', null),
    note('n6', 'six', null),
  ])
  assert.deepEqual(
    moc.split('\n').filter((l) => l.startsWith('## ')),
    ['## alpha', '## beta', '## untagged'],
  )
  // Members are id-asc within a section.
  assert.ok(moc.indexOf('## untagged\n- [[n4]] — four\n- [[n5]] — five\n- [[n6]] — six') !== -1)
})

test('both builders are deterministic — reversed input order yields byte-identical output', () => {
  const rNotes = [...NOTES].reverse()
  const rEdges = [...EDGES].reverse()
  assert.equal(
    buildTopicMoc(NOTES, EDGES, CLUSTERS),
    buildTopicMoc(rNotes, rEdges, detectCommunities({ notes: rNotes, edges: rEdges })),
  )
  assert.equal(buildOriginMoc(NOTES), buildOriginMoc([...NOTES].reverse()))
})

test('MOC output never contains the Related-block markers — whole files, not marker-managed blocks', () => {
  for (const moc of [buildTopicMoc(NOTES, EDGES, CLUSTERS), buildOriginMoc(NOTES)]) {
    assert.ok(!moc.includes(RELATED_BEGIN))
    assert.ok(!moc.includes(RELATED_END))
    assert.ok(!moc.includes('computed-links'))
  }
})

test('mocExcerpt skips a leading H1 that is the note title (loosely — filename sanitization)', () => {
  const body = '# Retry/reload wrapper cleanup: must special-case a WIN\n\nThe wrapper silently reloads the win away.\n'
  assert.equal(
    mocExcerpt(body, 'Retry-reload wrapper cleanup must special-case a WIN'),
    'The wrapper silently reloads the win away.',
  )
})

test('mocExcerpt keeps the first line when it is real prose, and is null for a title-only note', () => {
  assert.equal(mocExcerpt('Starts with prose, no heading.\n', 'Some Note'), 'Starts with prose, no heading.')
  assert.equal(mocExcerpt('# Some Note\n', 'Some Note'), null)
})
